let currentLang = "ar";
const $ = (id) => document.getElementById(id);
const t = (key) => translations[currentLang][key] || key;

function applyLanguage() {
  document.documentElement.lang = currentLang;
  document.documentElement.dir = currentLang === "ar" ? "rtl" : "ltr";
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.dataset.i18n;
    if (translations[currentLang][key]) el.innerHTML = translations[currentLang][key];
  });
  document.querySelectorAll("[data-placeholder]").forEach(el => {
    el.placeholder = t(el.dataset.placeholder);
  });
  $("languageToggle").textContent = currentLang === "ar" ? "EN" : "ع";
  $("crumbCurrent").textContent = document.querySelector(".nav-item.active span:last-child")?.textContent || t("writer");
}

$("languageToggle").addEventListener("click", () => {
  currentLang = currentLang === "ar" ? "en" : "ar";
  applyLanguage();
});

function showToast(message) {
  const toast = $("toast");
  toast.textContent = message;
  toast.classList.add("show");
  clearTimeout(showToast.timer);
  showToast.timer = setTimeout(() => toast.classList.remove("show"), 2600);
}

document.querySelectorAll(".nav-item").forEach(button => {
  button.addEventListener("click", () => {
    document.querySelectorAll(".nav-item").forEach(item => item.classList.remove("active"));
    button.classList.add("active");
    document.querySelectorAll(".nav-item").forEach(item => item.setAttribute("aria-current", item === button ? "page" : "false"));
    document.querySelectorAll(".page").forEach(page => page.classList.remove("active"));
    $("page-" + button.dataset.page).classList.add("active");
    $("crumbCurrent").textContent = button.querySelector("span:last-child").textContent;
    $("sidebar").classList.remove("open");
  });
});
$("menuToggle").addEventListener("click", () => $("sidebar").classList.toggle("open"));

async function checkApi() {
  $("apiStatus").textContent = t("checking");
  $("apiDot").style.background = "#e5ad54";
  try {
    const response = await fetch("/api/health", { headers: { "accept": "application/json" } });
    if (!response.ok) throw new Error("Health check failed");
    const data = await response.json();
    $("apiStatus").textContent = data.configured ? t("connected") : t("notConfigured");
    $("apiDot").style.background = data.configured ? "#5bd6a2" : "#e5ad54";
  } catch {
    $("apiStatus").textContent = t("connectionError");
    $("apiDot").style.background = "#ed7180";
  }
}
$("checkApi").addEventListener("click", checkApi);

function setBusy(button, busy, label) {
  button.disabled = busy;
  button.querySelector("span:nth-child(2)").textContent = label;
}

async function requestGeneration(payload) {
  const response = await fetch("/api/generate", {
    method: "POST",
    headers: { "content-type": "application/json" },
    body: JSON.stringify(payload)
  });
  const data = await response.json().catch(() => ({}));
  if (!response.ok) throw new Error(data.error || t("serverError"));
  if (typeof data.output !== "string" || !data.output.trim()) throw new Error(t("serverError"));
  return data.output.trim();
}

$("generatePost").addEventListener("click", async () => {
  const topic = $("topic").value.trim();
  if (!topic) return showToast(t("enterTopic"));
  const button = $("generatePost");
  $("postEmpty").classList.add("hidden");
  $("postResult").classList.add("hidden");
  $("postError").classList.add("hidden");
  $("postLoading").classList.remove("hidden");
  setBusy(button, true, currentLang === "ar" ? "جارٍ الإنشاء..." : "Generating...");
  try {
    const output = await requestGeneration({
      action: "post", topic, platform: $("platform").value, tone: $("tone").value,
      language: $("postLanguage").value === "en" ? "en" : "ar",
      length: $("length").value, audience: $("audience").value,
      keywords: $("keywords").value, callToAction: $("cta").value
    });
    $("postOutput").textContent = output;
    $("postResult").classList.remove("hidden");
  } catch (error) {
    $("postError").textContent = error.message;
    $("postError").classList.remove("hidden");
  } finally {
    $("postLoading").classList.add("hidden");
    setBusy(button, false, t("generatePost"));
  }
});

$("generateHashtags").addEventListener("click", async () => {
  const topic = $("hashTopic").value.trim();
  if (!topic) return showToast(t("enterTopic"));
  $("hashResult").classList.add("hidden");
  $("hashError").classList.add("hidden");
  $("hashLoading").classList.remove("hidden");
  const button = $("generateHashtags");
  setBusy(button, true, currentLang === "ar" ? "جارٍ الإنشاء..." : "Generating...");
  try {
    const output = await requestGeneration({
      action: "hashtags", topic, platform: $("hashPlatform").value,
      language: $("hashLanguage").value
    });
    $("hashOutput").textContent = output;
    $("hashResult").classList.remove("hidden");
  } catch (error) {
    $("hashError").textContent = error.message;
    $("hashError").classList.remove("hidden");
  } finally {
    $("hashLoading").classList.add("hidden");
    setBusy(button, false, t("generateHashtags"));
  }
});

async function copyText(text) {
  try {
    await navigator.clipboard.writeText(text);
    showToast(t("copied"));
  } catch {
    showToast(t("copyFailed"));
  }
}
$("copyPost").addEventListener("click", () => copyText($("postOutput").textContent));
$("copyHashtags").addEventListener("click", () => copyText($("hashOutput").textContent));

$("calculate").addEventListener("click", () => {
  const followers = Number($("followers").value);
  const likes = Number($("likes").value);
  const comments = Number($("comments").value);
  const shares = Number($("shares").value);
  if (![followers, likes, comments, shares].every(Number.isFinite) || [followers, likes, comments, shares].some(v => v < 0)) {
    return showToast(t("invalidStats"));
  }
  if (followers <= 0) return showToast(t("zeroFollowers"));
  const rate = ((likes + comments + shares) / followers) * 100;
  $("engValue").textContent = rate.toFixed(2) + "%";
  $("engAdvice").textContent = rate < 1 ? t("low") : rate < 4 ? t("average") : t("high");
  $("engResult").classList.remove("hidden");
});

